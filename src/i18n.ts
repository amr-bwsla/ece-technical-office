export type DictKey = keyof typeof dict

export function useT() {
  const lang = useStore((s) => s.lang)
  return {
    lang,
    t: (key: DictKey) => dict[key][lang],
    l: (v: Localized) => v[lang],
    tx: (s: string) => translate(s, lang),
  }
}

export function formatDuration(ms: number, lang: Lang) {
  const mins = Math.max(0, Math.round(Math.abs(ms) / 60000))
  const d = Math.floor(mins / 1440)
  const h = Math.floor((mins % 1440) / 60)
  const m = mins % 60
  const u = lang === 'ar' ? { d: 'ي', h: 'س', m: 'د' } : { d: 'd', h: 'h', m: 'm' }
  if (d) return `${d}${u.d} ${h}${u.h}`
  if (h) return `${h}${u.h} ${m}${u.m}`
  return `${m}${u.m}`
}

export function timeAgo(ts: number, lang: Lang) {
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' })
  const diff = (ts - Date.now()) / 1000
  const abs = Math.abs(diff)
  if (abs < 60) return rtf.format(Math.round(diff), 'second')
  if (abs < 3600) return rtf.format(Math.round(diff / 60), 'minute')
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), 'hour')
  return rtf.format(Math.round(diff / 86400), 'day')
}
